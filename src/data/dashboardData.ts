function getQuarter(month: string): string {
  const [yr, mm] = month.split('-')
  const m = parseInt(mm)
  const q = m <= 3 ? 1 : m <= 6 ? 2 : m <= 9 ? 3 : 4
  return `${yr}-Q${q}`
}

